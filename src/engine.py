import sys
from llm_sdk import Small_LLM_Model  # type: ignore
from .decoder import RestrictedDecoder
from typing import Dict, List, Any


class Engine:
    """
    Orchestrates the processing of natural language prompts into structured
    function calls.

    Attributes:
        model (Small_LLM_Model): The LLM instance used for generation.
        decoder (RestrictedDecoder): The decoder instance used for constrained
        generation.
    """
    def __init__(self,
                 model: Small_LLM_Model,
                 decoder: RestrictedDecoder) -> None:
        """
        Initializes the Engine with a model and a decoder.
        Args:
            model: The LLM model to be used.
            decoder: The restricted decoder for constrained generation.
        """
        self.model = model
        self.decoder = decoder

    def process(
        self,
        prompts: List[Dict[str, Any]],
        functions: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:
        """
        Processes a list of prompts against a set of function definitions.
        Args:
            prompts: A list of dictionaries, where each dict contains a
            "prompt" key.
            functions: A list of function schemas available for calling.
        Returns:
            A list of successfully processed results, each containing
            the original prompt, function name, and extracted parameters.
        """
        results: List[Dict[str, Any]] = []

        for prompt_data in prompts:
            prompt_text = prompt_data.get("prompt")

            if not prompt_text:
                print("Warning: Skipping empty prompt.", file=sys.stderr)
                continue

            try:
                result = self.decoder.run(prompt_text, functions)

                self._validate(result)
                results.append(result)

            except Exception as e:
                print(
                    f"Error processing prompt: '{prompt_text[:50]}...'."
                    f"Reason: {e}",
                    file=sys.stderr
                    )

        return results

    def _validate(self, result: Dict[str, Any]) -> None:
        """
        Validates the structure of the processed result.
        Args:
            result: The dictionary output generated by the decoder.
        Raises:
            ValueError: If the result is missing required keys
            ("prompt", "name", "parameters").
            TypeError: If "parameters" is not a dictionary.
        """
        required = {"prompt", "name", "parameters"}
        if not all(key in result for key in required):
            raise ValueError(
                f"Result missing required keys. Got: {list(result.keys())}"
                )

        if not isinstance(result["parameters"], Dict):
            raise TypeError("Result 'parameters' must be a dictionary.")
