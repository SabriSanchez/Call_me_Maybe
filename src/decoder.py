import json
from typing import Any, Dict, Tuple, Set, List
from llm_sdk import Small_LLM_Model  # type: ignore
from .tokenizer_utils import TokenizerUtils


class TrieNode:
    """
    Represents a node in a trie data structure for constrained decoding.

    Attributes:
        children (Dict[int, TrieNode]): Mapping of token IDs to child nodes.
        function_name (str | None): Name of the function if this node marks
                                    the end of a path.
    """
    def __init__(self) -> None:
        self.children: Dict[int, "TrieNode"] = {}
        self.function_name: str | None = None


class RestrictedDecoder:
    """
    Decoder that restricts LLM token generation to valid function calls
    and argument types.
    """
    def __init__(self,
                 model: Small_LLM_Model,
                 tokenizer: TokenizerUtils,
                 function_tokens: Dict[str, List[int]]) -> None:
        """
        Initializes the decoder with the model, tokenizer, and function
        definitions.
        """
        self.model = model
        self.tokenizer = tokenizer
        self.function_tokens = function_tokens

        self.trie = self._build_trie(self.function_tokens)

        (
            self.allowed_num_tokens,
            self.allowed_bool_tokens
        ) = self._build_vocab_masks()

    def _build_trie(self, function_tokens: Dict[str, List[int]]) -> TrieNode:
        """
        Builds a prefix tree (Trie) from the provided function token sequences.
        Args:
            function_tokens: A mapping from function names to their
            token ID lists.
        """
        root = TrieNode()
        for name, tokens in function_tokens.items():
            node = root
            for t in tokens:
                if t not in node.children:
                    node.children[t] = TrieNode()
                node = node.children[t]
            node.function_name = name
        return root

    def _build_vocab_masks(self) -> Tuple[Set[int], Set[int]]:
        """
        Scans the model vocabulary to identify tokens representing numbers
        or booleans.
        Returns:
            A tuple containing a set of token IDs for numbers and a set
            for booleans.
        """
        vocab_path = self.model.get_path_to_vocab_file()
        with open(vocab_path, "r", encoding="utf-8") as f:
            vocab = json.load(f)

        allowed_num = set()
        allowed_bool = set()

        newline_tokens = set(self.tokenizer.encode("\n"))

        for token_str, token_id in vocab.items():

            text = self.tokenizer.decode([token_id]).strip().lower()

            if not text:
                continue

            if all(c in "0123456789.-" for c in text):
                allowed_num.add(token_id)

            if text in ["true",
                        "false",
                        "t",
                        "f",
                        "ru",
                        "al",
                        "se",
                        "rue",
                        "lse"]:
                allowed_bool.add(token_id)

        allowed_num.update(newline_tokens)
        allowed_bool.update(newline_tokens)

        return allowed_num, allowed_bool

    def select_function(self, prompt: str,
                        functions_schema: List[Dict[str, Any]]) -> str:
        """
        Identifies the appropriate function for a given prompt using
        constrained decoding.
        Args:
            prompt: The natural language request.
            functions_schema: List of available function definitions.
        Returns:
            The name of the selected function.
        """
        tools_desc = ""
        for fn in functions_schema:
            tools_desc += f"- {fn['name']}: {fn['description']}\n"

        context_prompt = (
            f"You have the following tools available:\n"
            f"{tools_desc}\n"
            f"Identify the correct function to fulfill this request.\n"
            f"Request: {prompt}\n"
            f"Function name:"
        )

        current_ids = self.tokenizer.encode(context_prompt)
        node = self.trie

        while True:
            logits = self.model.get_logits_from_input_ids(current_ids)
            allowed = node.children.keys()

            for i in range(len(logits)):
                if i not in allowed:
                    logits[i] = float("-inf")

            next_token = max(range(len(logits)), key=lambda i: logits[i])
            current_ids.append(next_token)

            if next_token not in node.children:
                raise ValueError("Invalid function path generated by Trie")

            node = node.children[next_token]

            if node.function_name is not None:
                return node.function_name

    def _mask_logits(self,
                     logits: List[float],
                     allowed_tokens: set[int]) -> List[float]:
        """
        Applies a mask to logits to restrict the model to a subset of
        allowed tokens.
        Args:
            logits: List of raw model logits.
            allowed_tokens: Set of token IDs permitted to be selected.
        Returns:
            The masked logits list.
        """
        for i in range(len(logits)):
            if i not in allowed_tokens:
                logits[i] = float("-inf")
        return logits

    def extract_args(self, prompt: str,
                     function_schema: Dict[str, Any]) -> Dict[str, Any]:
        """
        Extracts arguments for a specific function based on the user prompt.
        Args:
            prompt: The user input.
            function_schema: The definition of the function to extract
            parameters for.
        Returns:
            A dictionary containing the extracted argument names and values.
        """
        result: Dict[str, Any] = {}
        for param_name, param_info in function_schema["parameters"].items():
            param_type = param_info["type"]
            value = self._decode_argument(
                prompt,
                function_schema,
                param_name,
                param_type,
                result
            )
            result[param_name] = value
        return result

    def _decode_argument(
        self, prompt: str,
        fn_schema: Dict[str, Any],
        param_name: str,
        param_type: str,
        previous_args: Dict[str, Any]
    ) -> Any:
        """
        Decodes a single argument value by generating tokens restricted
        by type.
        Args:
            prompt: The original user request.
            fn_schema: Schema of the target function.
            param_name: Name of the parameter to extract.
            param_type: The expected type of the parameter ('number', 'string',
            'boolean').
            previous_args: Already extracted arguments for context.
        Returns:
            The decoded argument value in the appropriate type.
        """
        prefix = ' "' if param_type == "string" else ' '

        name = fn_schema["name"]
        fn_desc = fn_schema.get("description", "")

        extracted_str = ""
        if previous_args:
            for k, v in previous_args.items():
                val_str = f'"{v}"' if isinstance(v, str) else v
                extracted_str += f"{k}: {val_str}\n"

        base_text = (
            f"Analyze the sentence and extract the correct parameters.\n"
            f"Sentence: {prompt}\n"
            f"Function: {name} ({fn_desc})\n"
            f"---\n"
            f"{extracted_str}"
            f"{param_name}:{prefix}"
        )

        current_ids = self.tokenizer.encode(base_text)
        generated: list[int] = []

        max_steps = 40

        for _ in range(max_steps):
            logits = self.model.get_logits_from_input_ids(current_ids)

            if param_type == "number":
                self._mask_logits(logits, self.allowed_num_tokens)
            elif param_type == "boolean":
                self._mask_logits(logits, self.allowed_bool_tokens)

            next_token = max(range(len(logits)), key=lambda i: logits[i])

            current_ids.append(next_token)
            generated.append(next_token)

            decoded_so_far = self.tokenizer.decode(generated)

            if '\n' in decoded_so_far:
                break

            if param_type == "string" and '"' in decoded_so_far:
                break

            if param_type == "boolean":
                text_eval = decoded_so_far.lower().strip()
                if "true" in text_eval or "false" in text_eval:
                    break

        raw_text = self.tokenizer.decode(generated)
        final_text = raw_text.split('\n')[0].split('"')[0].strip()

        if param_type == "number":
            try:
                return float(final_text)
            except ValueError:
                return 0.0

        if param_type == "boolean":
            return "true" in final_text.lower()

        return final_text

    def validate_output(self, result: Dict[str, Any]) -> None:
        """
        Validates the structure of the generated function call result.
        Args:
            result: The dictionary output generated by the decoder.
        Raises:
            ValueError: If required keys are missing.
            TypeError: If the 'parameters' value is not a dictionary.
        """

        required_keys = {"prompt", "name", "parameters"}

        if set(result.keys()) != required_keys:
            raise ValueError(f"Invalid output keys: {result.keys()}")

        if not isinstance(result["parameters"], dict):
            raise TypeError("parameters must be a dictionary")

    def run(self, prompt: str,
            functions_schema: List[dict[str, Any]]) -> Dict[str, Any]:
        """
        Processes a prompt to select a function and extract its arguments.
        Args:
            prompt: The natural language input.
            functions_schema: Available functions to choose from.
        Returns:
            A structured dictionary containing the prompt, function name,
            and arguments.
        """
        name = self.select_function(prompt, functions_schema)

        fn_schema = next(
            (f for f in functions_schema if f["name"] == name),
            None
        )

        if fn_schema is None:
            raise ValueError(f"Function not found: {name}")

        args = self.extract_args(prompt, fn_schema)

        final_result: Dict[str, Any] = {
            "prompt": prompt,
            "name": name,
            "parameters": args
        }
        return final_result
